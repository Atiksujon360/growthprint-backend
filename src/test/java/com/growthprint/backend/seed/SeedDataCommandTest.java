package com.growthprint.backend.seed;

import com.growthprint.backend.auth.entity.User;
import com.growthprint.backend.auth.entity.UserRole;
import com.growthprint.backend.auth.repository.UserRepository;
import com.growthprint.backend.support.entity.SupportRequest;
import com.growthprint.backend.support.repository.SupportRequestRepository;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.transaction.annotation.Transactional;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
@ActiveProfiles("seed")
@Transactional
public class SeedDataCommandTest {

    @Autowired
    private SeedDataCommand seedDataCommand;

    @Autowired
    private UserRepository userRepository;

    @Autowired
    private SupportRequestRepository supportRequestRepository;

    @Test
    public void testSeedDataCreatesAdminUser() {
        // First run should create data
        seedDataCommand.seedData();

        User admin = userRepository.findByNormalizedEmail("admin@growthprint.dev")
                .orElseThrow(() -> new AssertionError("Admin user not created"));

        assertEquals("admin@growthprint.dev", admin.getEmail());
        assertEquals(UserRole.ADMIN, admin.getRole());
    }

    @Test
    public void testSeedDataIsIdempotent() {
        // First run
        seedDataCommand.seedData();
        long userCountAfterFirst = userRepository.count();

        // Second run should skip
        seedDataCommand.seedData();
        long userCountAfterSecond = userRepository.count();

        assertEquals(userCountAfterFirst, userCountAfterSecond,
                "Seed data should be idempotent - no duplicate users on second run");
    }

    @Test
    public void testSupportRequestPersistence() {
        seedDataCommand.seedData();

        // Verify support requests were created without errors
        long supportRequestCount = supportRequestRepository.count();
        assertTrue(supportRequestCount > 0, "Support requests should be created");

        // Verify they can be fetched
        SupportRequest request = supportRequestRepository.findAll().get(0);
        assertNotNull(request.getId(), "SupportRequest should have ID generated by JPA");
        assertNotNull(request.getReference(), "SupportRequest should have reference");
    }
}
