package com.growthprint.backend.ai.triage;

import com.growthprint.backend.support.entity.BusinessImpact;
import com.growthprint.backend.support.entity.SupportCategory;
import com.growthprint.backend.support.entity.Urgency;
import io.swagger.v3.oas.annotations.media.Schema;

import java.time.Instant;
import java.util.UUID;

/**
 * An AI suggestion for a support request. Nothing here has been applied or sent: the admin reviews it and,
 * if they agree, applies it through the normal classify/status endpoints. The reply draft must be edited and
 * sent by a person.
 */
@Schema(description = "AI-generated suggestion for a support request (not applied, not sent)")
public record SupportTriageSuggestion(
        UUID requestId,
        SupportCategory category,
        Urgency urgency,
        BusinessImpact businessImpact,
        @Schema(description = "Short neutral summary of the client's issue") String summary,
        @Schema(description = "Draft reply for a human to review and edit; never sent automatically") String replyDraft,
        @Schema(description = "Always true: this content was generated by AI") boolean aiGenerated,
        String provider,
        String model,
        Instant generatedAt
) {
}
